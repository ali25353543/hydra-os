global beep_init
global beep
global beep_start
global beep_stop

; ============================================================
; دالة تهيئة المؤقت (تُستدعى مرة واحدة)
; ============================================================
beep_init:
    mov al, 0xB6        ; أمر التحكم: القناة 2، وضع الموجة المربعة
    out 0x43, al
    ret

; ============================================================
; دالة تشغيل الصوت
; المدخلات: [esp+4] = التردد المطلوب (مثلاً 1000 هرتز)
; ============================================================
beep_start:
    push ebp
    mov ebp, esp
    push eax
    push edx

    ; -------- حساب القيمة اللازمة للمؤقت --------
    ; القيمة = 1193180 / التردد
    mov eax, 1193180    ; تردد الساعة الأساسي
    mov edx, 0          ; تصفير EDX (المقسوم في EDX:EAX)
    mov ecx, [ebp+8]    ; التردد المطلوب (من المكدس)
    div ecx             ; EAX = القيمة, EDX = الباقي (نتجاهله)

    ; -------- إرسال القيمة إلى المؤقت --------
    out 0x42, al        ; إرسال البايت السفلي (LSB)
    mov al, ah
    out 0x42, al        ; إرسال البايت العلوي (MSB)

    ; -------- تشغيل مكبر الصوت --------
    in al, 0x61         ; قراءة حالة مكبر الصوت
    or al, 00000011b    ; تعيين البت 0 (تمكين المؤقت) والبت 1 (تمكين مكبر الصوت)
    out 0x61, al

    pop edx
    pop eax
    pop ebp
    ret

; ============================================================
; دالة إيقاف الصوت
; ============================================================
beep_stop:
    push eax
    in al, 0x61         ; قراءة حالة مكبر الصوت
    and al, 11111100b   ; إعادة تعيين البت 0 والبت 1
    out 0x61, al
    pop eax
    ret

; ============================================================
; دالة متكاملة (تشغيل + انتظار + إيقاف)
; المدخلات: [esp+4] = التردد, [esp+8] = المدة بالميلي ثانية
; ============================================================
beep:
    push ebp
    mov ebp, esp
    push eax
    push ebx
    push ecx
    push edx

    ; 1. تشغيل الصوت
    push dword [ebp+8]   ; تمرير التردد
    call beep_start
    add esp, 4

    ; 2. حلقة تأخير (تقريبية)
    mov ecx, [ebp+12]    ; المدة بالميلي ثانية
    mov eax, 1000        ; عدد التكرارات لكل ميلي ثانية (تقريبي)
    mul ecx              ; EAX = المدة * 1000
    mov ecx, eax

delay_loop:
    nop
    loop delay_loop
    call beep_stop

    pop edx
    pop ecx
    pop ebx
    pop eax
    pop ebp
    ret